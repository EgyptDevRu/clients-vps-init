#!/bin/bash
#
# Laravel queue workers for FASTPANEL site users, managed through Supervisord.
#
# Trust model:
#   - Site users edit worker configs in ~/supervisor/*.conf (their own files).
#   - Only root writes /etc/supervisor/conf.d. Root reads each user's files as
#     that user, accepts only an allow-list of [program:...] settings, and
#     renders /etc/supervisor/conf.d/worker-<user>.conf with user=, process
#     names and log paths forced. Supervisor writes logs into a root-owned
#     directory, so users cannot redirect root file writes via symlinks.
#
# Modes:
#   activate-worker.sh --all     root (cron, every 5 min):
#                                  - every SCAN_INTERVAL_MIN: migrate legacy
#                                    conf.d files and run the project scan as
#                                    each site user (setpriv: no PAM session,
#                                    no systemd --user)
#                                  - every run: validate users' configs, render
#                                    conf.d, supervisorctl reread/update only if
#                                    conf.d changed
#   activate-worker.sh           site user: project scan for this account
#   activate-worker.sh --export  site user (called by root): print ~/supervisor
#
# Project scan (per user, in ~/supervisor):
#   - Generated files start with "; managed-by=activate-worker sha256=<hash>";
#     while the hash matches they may be regenerated.
#   - Edited or renamed files belong to the user and are never rewritten; a
#     project already referenced by any file gets no new file.
#   - An empty (or comments-only) <project>.conf disables that project.
#   - Deleted files are recreated; files for removed projects are deleted.
#

set -euo pipefail
shopt -s nullglob

CONF_D="/etc/supervisor/conf.d"
STATE_DIR="/var/lib/activate-worker"
LOCK_FILE="/run/activate-worker.lock"
USER_LOG_ROOT="/var/log/supervisor/users"
USER_CONF_SUBDIR="supervisor"
SCAN_INTERVAL_MIN=30
SAFE_PATH_RE='^/[A-Za-z0-9_./-]+$'
MARKER_PREFIX="; managed-by=activate-worker sha256="
GENERATED_PREFIX="; generated by activate-worker for user="

# Limits applied by root when rendering a user's configs.
MAX_NUMPROCS=8
MAX_PROGRAMS_PER_USER=20
MAX_PROCS_PER_USER=16
MAX_STOPWAITSECS=3600
MAX_FILE_BYTES=16384
MAX_EXPORT_BYTES=262144

# True when the file has no settings at all (blank lines and ;/# comments only).
is_empty_conf() {
    [[ -r "$1" ]] && ! grep -qvE '^[[:space:]]*([;#].*)?$' "$1"
}

# ===========================================================================
# Site-user side
# ===========================================================================

resolve_php() {
    local candidates=(
        "${HOME}/bin/php"
        "/opt/php85/bin/php"
        "/opt/php84/bin/php"
        "/opt/php83/bin/php"
    )
    local bin
    for bin in "${candidates[@]}"; do
        if [[ -x "${bin}" ]]; then
            printf '%s' "${bin}"
            return 0
        fi
    done
    return 1
}

# Managed = marker on line 1 and its hash matches the rest of the file.
is_managed() {
    local file="$1" first="" expected actual
    IFS= read -r first < "${file}" || true
    [[ "${first}" == "${MARKER_PREFIX}"* ]] || return 1
    expected="${first#"${MARKER_PREFIX}"}"
    actual="$(tail -n +2 "${file}" | sha256sum | cut -d' ' -f1)"
    [[ "${actual}" == "${expected}" ]]
}

# Files in ~/supervisor (any name) whose content references this artisan path.
find_covering_confs() {
    local artisan="$1" conf
    for conf in "${USER_CONF_DIR}"/*.conf; do
        [[ -f "${conf}" ]] || continue
        if grep -qFw -- "${artisan}" "${conf}" 2>/dev/null; then
            printf '%s\n' "${conf}"
        fi
    done
}

render_body() {
    local name="$1" artisan="$2" project_root="$3"
    cat << EOF
; Queue worker for ${project_root}
; Edit freely: once changed, this file is yours and is never overwritten.
; Empty it (or leave only comments) to disable; delete it to get a fresh default.
; Logs: ${USER_LOG_ROOT}/${USER_NAME}/worker-${USER_NAME}-${name}.log
[program:${name}]
command=${PHP_BIN} ${artisan} queue:work --queue=telegram,default --sleep=3 --tries=3 --max-time=3600
directory=${project_root}
numprocs=2
autostart=true
autorestart=true
startsecs=1
stopasgroup=true
killasgroup=true
stopwaitsecs=3600
EOF
}

process_project() {
    local artisan="$1"
    local project_root name canonical covering body full

    project_root="$(dirname "${artisan}")"
    name="$(basename "${project_root}" | tr -cd 'A-Za-z0-9_')"
    canonical="${USER_CONF_DIR}/${name}.conf"

    echo "  Found Laravel: ${project_root}"

    if [[ -z "${name}" || ! "${artisan}" =~ ${SAFE_PATH_RE} ]]; then
        echo "    Path has unsupported characters; skipping (write a config by hand)."
        return 0
    fi

    if [[ -f "${canonical}" ]] && is_empty_conf "${canonical}"; then
        echo "    Disabled by user (empty ${canonical}); skipping."
        return 0
    fi

    if [[ ! -f "${canonical}" ]]; then
        covering="$(find_covering_confs "${artisan}")"
        if [[ -n "${covering}" ]]; then
            echo "    Covered by: ${covering//$'\n'/, }; skipping."
            return 0
        fi
    fi

    if [[ -z "${PHP_BIN}" ]]; then
        echo "    No usable PHP binary; cannot generate config."
        return 0
    fi

    body="$(mktemp)"
    full="$(mktemp)"
    render_body "${name}" "${artisan}" "${project_root}" > "${body}"
    {
        printf '%s%s\n' "${MARKER_PREFIX}" "$(sha256sum "${body}" | cut -d' ' -f1)"
        cat "${body}"
    } > "${full}"

    if [[ ! -f "${canonical}" ]]; then
        cat "${full}" > "${canonical}"
        echo "    Created: ${canonical}"
    elif is_managed "${canonical}"; then
        if ! cmp -s "${full}" "${canonical}"; then
            cat "${full}" > "${canonical}"
            echo "    Updated managed: ${canonical}"
        fi
    else
        echo "    Edited by user; leaving ${canonical} as-is."
    fi

    rm -f "${body}" "${full}"
}

# True if a command= line points at an artisan under ~/www that is gone.
references_missing_project() {
    local line word
    local -a words
    while IFS= read -r line; do
        read -ra words <<< "${line#*=}"
        for word in "${words[@]}"; do
            if [[ "${word}" == "${WWW_ROOT}/"*"/artisan" && ! -e "${word}" ]]; then
                return 0
            fi
        done
    done < <(grep -E '^[[:space:]]*command[[:space:]]*=' "$1" 2>/dev/null || true)
    return 1
}

cleanup_removed_projects() {
    local conf
    for conf in "${USER_CONF_DIR}"/*.conf; do
        [[ -f "${conf}" && -O "${conf}" ]] || continue
        if references_missing_project "${conf}"; then
            rm -f "${conf}"
            echo "  Removed config for missing project: ${conf}"
        fi
    done
}

# Rewrite already-migrated old-style files in ~/supervisor (in place).
normalize_legacy_user_files() {
    local conf tmp
    [[ -d "${USER_CONF_DIR}" ]] || return 0
    for conf in "${USER_CONF_DIR}"/*.conf; do
        [[ -f "${conf}" && -O "${conf}" ]] || continue
        looks_like_legacy_worker "${conf}" || continue
        tmp="$(mktemp)"
        if legacy_to_user_conf "${USER_NAME}" < "${conf}" > "${tmp}" 2>/dev/null; then
            cat "${tmp}" > "${conf}"
            echo "  Normalized legacy config: ${conf}"
        fi
        rm -f "${tmp}"
    done
}

user_scan() {
    USER_NAME="$(whoami)"
    WWW_ROOT="${HOME}/www"
    USER_CONF_DIR="${HOME}/${USER_CONF_SUBDIR}"

    echo "=== Scanning projects for user: ${USER_NAME} ==="

    mkdir -p "${USER_CONF_DIR}"
    normalize_legacy_user_files

    if [[ ! -d "${WWW_ROOT}" ]]; then
        echo "No ~/www directory."
        cleanup_removed_projects
        return 0
    fi

    PHP_BIN=""
    if PHP_BIN="$(resolve_php)"; then
        echo "Using PHP: ${PHP_BIN}"
        if [[ ! "${PHP_BIN}" =~ ${SAFE_PATH_RE} ]]; then
            echo "PHP path has unsupported characters; not generating configs."
            PHP_BIN=""
        fi
    else
        PHP_BIN=""
        echo "No usable PHP binary found (checked \$HOME/bin/php, /opt/php85|84|83/bin/php)."
    fi

    local artisan found=0
    while IFS= read -r -d '' artisan; do
        process_project "${artisan}"
        found=$((found + 1))
    done < <(find "${WWW_ROOT}" -maxdepth 4 -name artisan -type f -print0 2>/dev/null)

    cleanup_removed_projects

    echo "=== Done (${found} project(s)). Changes apply within 5 minutes. ==="
}

# Prints every ~/supervisor/*.conf for root, framed by "@@FILE <name>" lines.
user_export() {
    local dir="${HOME}/${USER_CONF_SUBDIR}" conf count=0
    [[ -d "${dir}" ]] || return 0
    for conf in "${dir}"/*.conf; do
        [[ -f "${conf}" ]] || continue
        count=$((count + 1))
        [[ "${count}" -le 50 ]] || break
        printf '@@FILE %s\n' "$(basename "${conf}")"
        head -c "${MAX_FILE_BYTES}" "${conf}" 2>/dev/null || true
        printf '\n'
    done
}

# ===========================================================================
# Root side
# ===========================================================================

log() {
    echo "$*"
    logger -t activate-worker -- "$*" 2>/dev/null || true
}

declare -A SITE_UID=() SITE_GID=() SITE_HOME=() UID_NAME=()

load_site_users() {
    local usr uid gid home
    while IFS=: read -r usr _ uid gid _ home _; do
        [[ "${uid}" =~ ^[0-9]+$ ]] || continue
        [[ "${uid}" -ge 1000 && "${uid}" -lt 60000 && "${usr}" != "nobody" ]] || continue
        [[ "${usr}" =~ ^[a-z_][a-z0-9_-]*$ ]] || continue
        [[ -n "${home}" && "${home}" == /* && -d "${home}" ]] || continue
        SITE_UID["${usr}"]="${uid}"
        SITE_GID["${usr}"]="${gid}"
        SITE_HOME["${usr}"]="${home}"
        UID_NAME["${uid}"]="${usr}"
    done < <(getent passwd)
}

# run_as <user> <timeout-seconds> <command...>
# setpriv switches uid/gid without a PAM session (unlike su/sudo/runuser).
# env -i instead of setpriv --reset-env: the latter needs util-linux >= 2.33.
run_as() {
    local usr="$1" limit="$2"
    shift 2
    timeout --kill-after=5 "${limit}" \
        setpriv \
            --reuid="${SITE_UID[${usr}]}" \
            --regid="${SITE_GID[${usr}]}" \
            --init-groups \
            --no-new-privs \
            -- \
        env -i HOME="${SITE_HOME[${usr}]}" USER="${usr}" LOGNAME="${usr}" \
            PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin" \
        "$@"
}

confd_hash() {
    find "${CONF_D}" -maxdepth 1 -name '*.conf' -print0 \
        | sort -z \
        | xargs -0 -r sha256sum \
        | sha256sum \
        | cut -d' ' -f1
}

# True when the file still looks like an old conf.d worker (server-owned keys).
looks_like_legacy_worker() {
    grep -qE '^(user|process_name|redirect_stderr|stdout_logfile)=' "$1" 2>/dev/null
}

# Rewrite an old conf.d-style worker into a clean ~/supervisor file (stdout).
# Drops user=/process_name=/logging; shortens [program:worker-USER-NAME].
legacy_to_user_conf() {
    local usr="$1" line key value name cmd artisan dir
    local prog="" body="" has_cmd=0 has_dir=0

    while IFS= read -r line || [[ -n "${line}" ]]; do
        line="${line%$'\r'}"
        [[ "${line}" =~ ^[[:space:]]*([;#].*)?$ ]] && continue

        if [[ "${line}" =~ ^\[program:([^]]+)\][[:space:]]*$ ]]; then
            name="${BASH_REMATCH[1]}"
            name="${name#"worker-${usr}-"}"
            [[ "${name}" =~ ^[A-Za-z0-9_-]{1,64}$ ]] || return 1
            prog="${name}"
            continue
        fi
        [[ -n "${prog}" ]] || continue
        [[ "${line}" =~ ^([a-z_]+)[[:space:]]*=[[:space:]]*(.*)$ ]] || continue
        key="${BASH_REMATCH[1]}"
        value="${BASH_REMATCH[2]}"
        value="${value%"${value##*[![:space:]]}"}"

        case "${key}" in
            user|process_name|redirect_stderr|stdout_*|stderr_*) continue ;;
            command)
                body+="command=${value}"$'\n'
                has_cmd=1
                cmd="${value}"
                ;;
            directory)
                body+="directory=${value}"$'\n'
                has_dir=1
                ;;
            numprocs|numprocs_start|priority|autostart|autorestart|startsecs|startretries|exitcodes|stopsignal|stopwaitsecs|stopasgroup|killasgroup|environment|umask)
                body+="${key}=${value}"$'\n'
                ;;
        esac
    done

    [[ -n "${prog}" && "${has_cmd}" -eq 1 ]] || return 1

    # Old templates had no directory=; derive it from the artisan path in command=.
    if [[ "${has_dir}" -eq 0 ]]; then
        artisan="$(awk '{ for (i = 1; i <= NF; i++) if ($i ~ /\/artisan$/) { print $i; exit } }' <<< "${cmd}")"
        if [[ -n "${artisan}" ]]; then
            dir="$(dirname "${artisan}")"
            body="directory=${dir}"$'\n'"${body}"
        fi
    fi

    printf '%s\n' "; Migrated from the old conf.d layout. Edit freely."
    printf '[program:%s]\n' "${prog}"
    printf '%s' "${body}"
}

# The worker config written by older versions of this script (users wrote it
# straight into conf.d). Unedited copies are dropped and regenerated.
is_legacy_generated() {
    local file="$1" usr="$2" prog cmd php rest artisan expected
    prog="$(sed -n 's/^\[program:\(.*\)\]$/\1/p;T;q' "${file}")"
    cmd="$(sed -n 's/^command=//p;T;q' "${file}")"
    [[ -n "${prog}" && -n "${cmd}" ]] || return 1
    php="${cmd%% *}"
    rest="${cmd#* }"
    artisan="${rest%% *}"
    expected="$(cat << EOF
[program:${prog}]
process_name=%(program_name)s_%(process_num)02d
command=${php} ${artisan} queue:work --queue=telegram,default --sleep=3 --tries=3 --max-time=3600
autostart=true
startsecs=1
autorestart=true
stopasgroup=true
killasgroup=true
user=${usr}
numprocs=2
redirect_stderr=true
stdout_logfile=$(dirname "${artisan}")/storage/logs/worker.log
stopwaitsecs=3600
EOF
)"
    [[ "$(cat "${file}")" == "${expected}" ]]
}

# Anything in conf.d not owned by root was written by a site user under the
# old model. Edited configs move to the owner's ~/supervisor; the rest goes.
migrate_legacy_confd() {
    local entry name owner usr target cleaned
    for entry in "${CONF_D}"/* "${CONF_D}"/.[!.]*; do
        name="$(basename "${entry}")"
        if [[ -L "${entry}" ]]; then
            rm -f "${entry}"
            log "Removed symlink ${entry}"
            continue
        fi
        [[ -f "${entry}" ]] || continue
        owner="$(stat -c %u "${entry}")"
        [[ "${owner}" -ne 0 ]] || continue

        usr="${UID_NAME[${owner}]:-}"
        if [[ -n "${usr}" && "${name}" == *.conf && "$(stat -c %h "${entry}")" -eq 1 ]] \
            && ! is_empty_conf "${entry}" && ! is_legacy_generated "${entry}" "${usr}"; then
            target="migrated-${name}"
            cleaned="$(mktemp)"
            if legacy_to_user_conf "${usr}" < "${entry}" > "${cleaned}" 2>/dev/null; then
                if run_as "${usr}" 10 /bin/bash -c \
                    'umask 077; mkdir -p "$HOME/$1" && set -o noclobber && cat > "$HOME/$1/$2"' \
                    _ "${USER_CONF_SUBDIR}" "${target}" < "${cleaned}"; then
                    log "Moved edited ${entry} to ~${usr}/${USER_CONF_SUBDIR}/${target}"
                else
                    log "warning: could not move ${entry} to ~${usr}/${USER_CONF_SUBDIR}; removing it"
                fi
            else
                log "warning: could not rewrite ${entry}; removing it"
            fi
            rm -f "${cleaned}"
        fi
        rm -f "${entry}"
        log "Removed user-owned ${entry}"
    done
}

scan_all_users() {
    local usr rc
    migrate_legacy_confd
    for usr in "${!SITE_UID[@]}"; do
        echo ">>> scan ${usr}"
        rc=0
        run_as "${usr}" 300 /bin/bash "${SELF}" </dev/null || rc=$?
        if [[ "${rc}" -ne 0 ]]; then
            log "warning: project scan failed for ${usr} (exit ${rc})"
        fi
    done
    touch "${STATE_DIR}/last-scan"
}

# Mirrors shlex.split (posix) failure cases Supervisor would hit at reread.
shell_quotes_balanced() {
    local s="$1" i c state="" len="${#1}"
    for ((i = 0; i < len; i++)); do
        c="${s:i:1}"
        if [[ "${state}" == "'" ]]; then
            if [[ "${c}" == "'" ]]; then state=""; fi
        elif [[ "${c}" == "\\" ]]; then
            if (( i + 1 >= len )); then return 1; fi
            i=$((i + 1))
        elif [[ "${state}" == '"' ]]; then
            if [[ "${c}" == '"' ]]; then state=""; fi
        elif [[ "${c}" == "'" || "${c}" == '"' ]]; then
            state="${c}"
        fi
    done
    [[ -z "${state}" ]]
}

# --- render_user_conf helpers (use its locals through bash dynamic scoping) ---

_note() {
    printf '%s: %s\n' "${file}" "$1" >> "${err}"
}

_reject_file() {
    if [[ "${file_ok}" -eq 1 ]]; then
        _note "REJECTED, not loaded: $1"
    fi
    file_ok=0
}

_add_setting() {
    local key="$1" value="$2"
    # Only reject % on values we actually copy; ignored keys (process_name,
    # stdout_logfile, …) may still contain Supervisor expansions from old files.
    if [[ "${value}" == *%* ]]; then
        _reject_file "'%' is not allowed (in ${key}=)"
        return 0
    fi
    if [[ " ${prog_keys} " == *" ${key} "* ]]; then
        _reject_file "[program:${prog}] sets ${key} twice"
        return 0
    fi
    prog_keys+=" ${key}"
    prog_text+="${key}=${value}"$'\n'
}

_flush_prog() {
    if [[ -n "${prog}" && "${file_ok}" -eq 1 ]]; then
        if [[ "${prog_has_cmd}" -eq 0 ]]; then
            _reject_file "[program:${prog}] has no command="
        else
            local full="worker-${usr}-${prog}"
            file_text+="[program:${full}]"$'\n'"${prog_text}"
            file_text+="process_name=%(program_name)s_%(process_num)02d"$'\n'
            file_text+="numprocs=${prog_procs}"$'\n'
            file_text+="user=${usr}"$'\n'
            file_text+="redirect_stderr=true"$'\n'
            file_text+="stdout_logfile=${USER_LOG_ROOT}/${usr}/${full}.log"$'\n'
            file_text+="stdout_logfile_maxbytes=10MB"$'\n'
            file_text+="stdout_logfile_backups=3"$'\n\n'
            file_names+=" ${prog}"
            file_procs=$((file_procs + prog_procs))
        fi
    fi
    prog=""
    prog_text=""
    prog_keys=""
    prog_has_cmd=0
    prog_procs=1
}

_flush_file() {
    _flush_prog
    if [[ -n "${file}" && "${file_ok}" -eq 1 && -n "${file_names}" ]]; then
        local n count=0
        local -A in_file=()
        for n in ${file_names}; do
            if [[ -n "${seen[${n}]+x}" || -n "${in_file[${n}]+x}" ]]; then
                _reject_file "[program:${n}] is already defined${seen[${n}]+ in ${seen[${n}]}}"
                break
            fi
            in_file["${n}"]=1
            count=$((count + 1))
        done
        if [[ "${file_ok}" -eq 1 ]] && (( total_progs + count > MAX_PROGRAMS_PER_USER )); then
            _reject_file "more than ${MAX_PROGRAMS_PER_USER} programs per user"
        fi
        if [[ "${file_ok}" -eq 1 ]] && (( total_procs + file_procs > MAX_PROCS_PER_USER )); then
            _reject_file "more than ${MAX_PROCS_PER_USER} processes per user in total"
        fi
        if [[ "${file_ok}" -eq 1 ]]; then
            for n in ${file_names}; do
                seen["${n}"]="${file}"
            done
            total_progs=$((total_progs + count))
            total_procs=$((total_procs + file_procs))
            printf '%s' "${file_text}" >> "${out}"
        fi
    fi
    file=""
    file_ok=0
    file_text=""
    file_names=""
    file_procs=0
}

# Validates one user's exported files and writes the Supervisor config body to
# $4 and human-readable problems to $5. Only allow-listed settings are copied;
# user=, process names and logging are always set here, never by the user.
render_user_conf() {
    local usr="$1" home="$2" input="$3" out="$4" err="$5"
    local line key value name
    local file="" file_ok=0 file_text="" file_names="" file_procs=0
    local prog="" prog_text="" prog_keys="" prog_has_cmd=0 prog_procs=1
    local total_progs=0 total_procs=0
    local -A seen=()

    local re_file='^[A-Za-z0-9_.-]{1,100}\.conf$'
    local re_section='^\[program:([A-Za-z0-9_-]{1,64})\][[:space:]]*$'
    local re_name='^[A-Za-z0-9_-]{1,64}$'
    local re_kv='^([a-z_]+)[[:space:]]*=[[:space:]]*(.*)$'
    local re_comment='^[[:space:]]*([;#].*)?$'
    local re_uint='^[0-9]{1,6}$'
    local re_env_pair='[A-Za-z_][A-Za-z0-9_]*=("[^"\\]*"|[^,"'"'"'\\[:space:]]*)'
    local re_env="^${re_env_pair}(,${re_env_pair})*$"

    : > "${out}"
    : > "${err}"

    while IFS= read -r line || [[ -n "${line}" ]]; do
        line="${line%$'\r'}"

        if [[ "${line}" == "@@FILE "* ]]; then
            _flush_file
            file="${line#@@FILE }"
            file_ok=1
            if [[ ! "${file}" =~ ${re_file} ]]; then
                file="${file//[^A-Za-z0-9_.-]/?}"
                _reject_file "unsupported file name"
            fi
            continue
        fi
        [[ -n "${file}" && "${file_ok}" -eq 1 ]] || continue
        [[ "${line}" =~ ${re_comment} ]] && continue

        if [[ "${line}" =~ ^[[:space:]] ]]; then
            _reject_file "indented (continuation) lines are not allowed"
            continue
        fi

        if [[ "${line}" =~ ${re_section} ]]; then
            _flush_prog
            name="${BASH_REMATCH[1]}"
            name="${name#"worker-${usr}-"}"
            if [[ ! "${name}" =~ ${re_name} ]]; then
                _reject_file "invalid program name"
                continue
            fi
            prog="${name}"
            continue
        fi
        if [[ "${line}" == "["* ]]; then
            _reject_file "only [program:NAME] sections are allowed"
            continue
        fi
        if [[ ! "${line}" =~ ${re_kv} ]]; then
            _reject_file "cannot parse line: ${line:0:80}"
            continue
        fi
        key="${BASH_REMATCH[1]}"
        value="${BASH_REMATCH[2]}"
        value="${value%"${value##*[![:space:]]}"}"

        if [[ -z "${prog}" ]]; then
            _reject_file "${key}= appears before any [program:NAME] section"
            continue
        fi

        case "${key}" in
            # Always set by root when rendering — ignore even if they contain %.
            user|process_name|redirect_stderr|stdout_*|stderr_*)
                _note "note: ${key}= is set by the server and was ignored"
                ;;
            command)
                if [[ -z "${value}" ]] || ! shell_quotes_balanced "${value}"; then
                    _reject_file "command= is empty or has unbalanced quotes"
                    continue
                fi
                _add_setting command "${value}"
                prog_has_cmd=1
                ;;
            numprocs)
                if [[ ! "${value}" =~ ${re_uint} ]] || (( 10#${value} < 1 || 10#${value} > MAX_NUMPROCS )); then
                    _reject_file "numprocs must be 1..${MAX_NUMPROCS}"
                    continue
                fi
                if [[ " ${prog_keys} " == *" numprocs "* ]]; then
                    _reject_file "[program:${prog}] sets numprocs twice"
                    continue
                fi
                prog_keys+=" numprocs"
                prog_procs=$((10#${value}))
                ;;
            numprocs_start|priority|startsecs|startretries)
                if [[ ! "${value}" =~ ${re_uint} ]]; then
                    _reject_file "${key} must be a number"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            stopwaitsecs)
                if [[ ! "${value}" =~ ${re_uint} ]] || (( 10#${value} > MAX_STOPWAITSECS )); then
                    _reject_file "stopwaitsecs must be 0..${MAX_STOPWAITSECS}"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            autostart|stopasgroup|killasgroup)
                if [[ "${value}" != "true" && "${value}" != "false" ]]; then
                    _reject_file "${key} must be true or false"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            autorestart)
                if [[ ! "${value}" =~ ^(true|false|unexpected)$ ]]; then
                    _reject_file "autorestart must be true, false or unexpected"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            exitcodes)
                if [[ ! "${value}" =~ ^[0-9]{1,3}(,[0-9]{1,3})*$ ]]; then
                    _reject_file "exitcodes must look like 0,2"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            stopsignal)
                if [[ ! "${value}" =~ ^(TERM|HUP|INT|QUIT|KILL|USR1|USR2)$ ]]; then
                    _reject_file "stopsignal must be TERM, HUP, INT, QUIT, KILL, USR1 or USR2"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            umask)
                if [[ ! "${value}" =~ ^0?[0-7]{3}$ ]]; then
                    _reject_file "umask must look like 022"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            directory)
                if [[ ! "${value}" =~ ${SAFE_PATH_RE} || "/${value}/" == *"/../"* ]] \
                    || [[ "${value}" != "${home}" && "${value}" != "${home}/"* ]]; then
                    _reject_file "directory must be inside ${home}"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            environment)
                if [[ ! "${value}" =~ ${re_env} ]]; then
                    _reject_file "environment must look like KEY=\"value\",OTHER=value"
                    continue
                fi
                _add_setting "${key}" "${value}"
                ;;
            *)
                _note "note: ${key}= is not supported and was ignored"
                ;;
        esac
    done < "${input}"
    _flush_file
}

remove_generated() {
    local dest="$1"
    if [[ -f "${dest}" ]]; then
        rm -f "${dest}"
        log "Removed ${dest}"
    fi
}

# Writes $2 to $1 only when content differs (root-owned, mode $3).
replace_if_changed() {
    local dest="$1" src="$2" mode="$3" tmp
    if [[ -f "${dest}" && ! -L "${dest}" ]] && cmp -s "${src}" "${dest}"; then
        return 1
    fi
    tmp="$(mktemp "$(dirname "${dest}")/.activate-worker.XXXXXX")"
    cat "${src}" > "${tmp}"
    chmod "${mode}" "${tmp}"
    mv -f "${tmp}" "${dest}"
}

sync_user() {
    local usr="$1"
    local home="${SITE_HOME[${usr}]}" gid="${SITE_GID[${usr}]}"
    local dest="${CONF_D}/worker-${usr}.conf"
    local log_dir="${USER_LOG_ROOT}/${usr}"
    local tmp_dir rc=0

    # Root only checks existence here; contents are read as the user below.
    if [[ ! -d "${home}/${USER_CONF_SUBDIR}" ]]; then
        remove_generated "${dest}"
        return 0
    fi

    tmp_dir="$(mktemp -d)"
    run_as "${usr}" 30 /bin/bash "${SELF}" --export </dev/null \
        | head -c "${MAX_EXPORT_BYTES}" > "${tmp_dir}/export" || rc=$?
    if [[ "${rc}" -ne 0 ]]; then
        log "warning: could not read ~${usr}/${USER_CONF_SUBDIR} (exit ${rc}); keeping current config"
        rm -rf "${tmp_dir}"
        return 0
    fi

    render_user_conf "${usr}" "${home}" "${tmp_dir}/export" "${tmp_dir}/body" "${tmp_dir}/errors"

    if [[ ! -d "${log_dir}" ]]; then
        install -d -m 750 -o root -g "${gid}" "${log_dir}"
    fi
    if replace_if_changed "${log_dir}/activate-worker.log" "${tmp_dir}/errors" 640; then
        chgrp "${gid}" "${log_dir}/activate-worker.log"
        if [[ -s "${tmp_dir}/errors" ]]; then
            log "Config problems for ${usr}: see ${log_dir}/activate-worker.log"
        fi
    fi

    # A typo must not stop running workers: keep the last good config until fixed.
    if [[ -f "${dest}" ]] && grep -q 'REJECTED' "${tmp_dir}/errors"; then
        rm -rf "${tmp_dir}"
        return 0
    fi

    if [[ -s "${tmp_dir}/body" ]]; then
        {
            printf '%s%s\n' "${GENERATED_PREFIX}" "${usr}"
            printf '; Do not edit: rendered from ~%s/%s/*.conf every 5 minutes.\n\n' "${usr}" "${USER_CONF_SUBDIR}"
            cat "${tmp_dir}/body"
        } > "${tmp_dir}/conf"
        if replace_if_changed "${dest}" "${tmp_dir}/conf" 644; then
            log "Updated ${dest}"
        fi
    else
        remove_generated "${dest}"
    fi

    rm -rf "${tmp_dir}"
}

# Generated files whose account is gone (or no longer a site user).
cleanup_generated_orphans() {
    local conf first usr
    for conf in "${CONF_D}"/worker-*.conf; do
        [[ -f "${conf}" && ! -L "${conf}" && "$(stat -c %u "${conf}")" -eq 0 ]] || continue
        first=""
        IFS= read -r first < "${conf}" || true
        [[ "${first}" == "${GENERATED_PREFIX}"* ]] || continue
        usr="${first#"${GENERATED_PREFIX}"}"
        if [[ -z "${SITE_UID[${usr}]+x}" ]]; then
            rm -f "${conf}"
            log "Removed ${conf} (account ${usr} no longer exists)"
        fi
    done
}

apply_if_changed() {
    local current stored="" out
    current="$(confd_hash)"
    [[ -f "${STATE_DIR}/confd.sha256" ]] && stored="$(<"${STATE_DIR}/confd.sha256")"

    if [[ "${current}" == "${stored}" ]]; then
        echo "conf.d unchanged; skipping supervisorctl."
        return 0
    fi

    echo "conf.d changed; applying..."
    if ! out="$(supervisorctl reread 2>&1 && supervisorctl update 2>&1)" || [[ "${out}" == *ERROR* ]]; then
        log "supervisorctl failed: ${out//$'\n'/ | }"
    else
        echo "${out}"
    fi
    # Stored even on failure so a persistent error does not retry every tick.
    printf '%s\n' "${current}" > "${STATE_DIR}/confd.sha256"
}

root_main() {
    if [[ "${EUID}" -ne 0 ]]; then
        echo "activate-worker.sh --all must run as root" >&2
        exit 1
    fi

    exec 9>"${LOCK_FILE}"
    if ! flock -n 9; then
        echo "Another activate-worker run is in progress; exiting."
        exit 0
    fi

    umask 022
    SELF="$(readlink -f "$0")"
    mkdir -p "${STATE_DIR}" "${USER_LOG_ROOT}"
    chmod 700 "${STATE_DIR}"
    load_site_users

    # 2-minute slack so cron's 5-minute ticks do not stretch the interval to 35.
    if [[ -z "$(find "${STATE_DIR}/last-scan" -mmin "-$((SCAN_INTERVAL_MIN - 2))" 2>/dev/null)" ]]; then
        echo "Full scan due."
        scan_all_users
    fi

    local usr
    for usr in "${!SITE_UID[@]}"; do
        sync_user "${usr}"
    done
    cleanup_generated_orphans

    apply_if_changed
}

case "${1:-}" in
    --all) root_main ;;
    --export) user_export ;;
    "")
        if [[ "${EUID}" -eq 0 ]]; then
            echo "As root, use: activate-worker.sh --all" >&2
            exit 1
        fi
        user_scan
        ;;
    *)
        echo "Usage: activate-worker.sh [--all | --export]" >&2
        exit 1
        ;;
esac
